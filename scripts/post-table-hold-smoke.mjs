import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const base=process.env.RADAR_QA_URL??'http://127.0.0.1:3003';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Bogota'}).format(new Date());
const catalog=Array.from({length:65},(_,i)=>({post_id:`POST-${String(i).padStart(4,'0')}`,nombre_creativo:`Publicación ${i}`,producto:'Pulsar 180',campana:'',plataforma:'Otra',activo:true,fecha_inicio:day.slice(0,7)+'-01'}));
const snapshot={mode:'live',profile:{user_id:'qa',nombre:'QA',email:'',role:'analista',activo:true},runs:[],catalog,sales:[],interactions:[]};
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1200,height:900}});
page.setDefaultTimeout(30000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.route('**/api/snapshot?**',route=>route.fulfill({json:snapshot}));
await page.route('**/api/meta**',route=>route.fulfill({json:{ads:[]}}));
mkdirSync('tmp/qa',{recursive:true});
try{
 await page.clock.install();
 await page.goto(base+'/post-id',{waitUntil:'domcontentloaded'});
 await page.locator('.posts-table tbody tr').last().waitFor();
 const next=page.getByRole('button',{name:'Ver columnas siguientes',exact:true});
 const previous=page.getByRole('button',{name:'Ver columnas anteriores',exact:true});
 const slider=page.getByRole('slider',{name:'Desplazar columnas de Post ID'});
 await next.waitFor();
 await page.clock.pauseAt(await page.evaluate(()=>Date.now()+10000));
 const position=()=>page.locator('.posts-scroll-viewport').evaluate(el=>el.scrollLeft);
 const maximum=await page.locator('.posts-scroll-viewport').evaluate(el=>el.scrollWidth-el.clientWidth);
 const press=async button=>{const box=await button.boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down()};
 const stable=async()=>{const stopped=await position();await page.clock.runFor(500);assert(Math.abs(await position()-stopped)<=1,'Scrolling must stop immediately')};
 await next.click();
 assert(await position()>=35&&await position()<85,'A brief click moves a small distance');
 await slider.focus();await slider.press('Home');
 await press(next);await page.clock.runFor(500);const first=await position();
 assert(first>100&&first<170,'Hold moves at a readable speed: '+first);
 await page.clock.runFor(500);const second=await position();
 assert(second>first+65&&second<first+115&&second<maximum,'Holding continues steadily without jumping to the end');
 await page.mouse.up();await stable();
 await press(previous);await page.clock.runFor(500);await page.mouse.up();
 assert(await position()<second-100,'Left arrow moves in the opposite direction');await stable();
 await next.focus();await page.keyboard.down('Space');await page.clock.runFor(300);await page.keyboard.up('Space');await stable();
 await press(next);await page.clock.runFor(100);await next.dispatchEvent('pointercancel');await stable();await page.mouse.up();
 await press(next);await page.clock.runFor(100);await page.evaluate(()=>window.dispatchEvent(new Event('blur')));await stable();await page.mouse.up();
 await page.locator('.posts-scroll-viewport').evaluate(el=>el.scrollLeft=el.scrollWidth-el.clientWidth-80);await page.clock.runFor(50);await press(next);await page.clock.runFor(1000);await page.mouse.up();
 const end=await page.locator('.posts-scroll-viewport').evaluate(el=>({left:el.scrollLeft,max:el.scrollWidth-el.clientWidth}));assert(Math.abs(end.left-end.max)<=2,'Stops at the right boundary: '+JSON.stringify(end));assert(await next.isDisabled());
 await press(previous);await page.clock.runFor(15000);await page.mouse.up();assert(await position()<=1);assert(await previous.isDisabled());
 await next.dispatchEvent('click');assert(await position()>=35,'Assistive click remains supported');
 assert.deepEqual(errors,[]);
 console.log('PASS: short click, steady hold in both directions, immediate release, keyboard, pointer cancellation, window blur, boundaries and assistive activation.');
}finally{await browser.close()}
