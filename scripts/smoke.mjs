import { mkdirSync, writeFileSync } from 'node:fs';
import {chromium} from 'playwright';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
page.setDefaultTimeout(15000);
console.log('Browser launched.');
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(condition,message)=>{if(!condition)throw Error(message)};
mkdirSync('tmp/qa',{recursive:true});
try{
 await page.goto('http://127.0.0.1:3000/inicio?demo=1',{waitUntil:'networkidle',timeout:60000});
 await page.getByRole('heading',{name:'Inicio',exact:true}).waitFor();
 check(await page.getByText('692',{exact:true}).count()>0,'Expected 692 demo orders');
 await page.screenshot({path:'tmp/qa/inicio-desktop.png',fullPage:true});
 console.log('Dashboard rendered.');
 await page.getByRole('link',{name:'Ver todos',exact:true}).click();
 await page.getByRole('heading',{name:'Post ID',exact:true}).waitFor();
 await page.getByRole('button',{name:'Sin ventas',exact:true}).click();
 check(await page.locator('table tbody tr').count()===2,'Zero-sale filter must show 2 posts');
 await page.getByRole('button',{name:'Todos',exact:true}).click();
 await page.getByRole('textbox',{name:'Buscar Post ID',exact:true}).fill('IG-240811');
 check(await page.locator('table tbody tr').count()===1,'Search must filter to 1 post');
 await page.locator('table tbody tr').first().click();
 await page.getByRole('dialog').waitFor();
 await page.screenshot({path:'tmp/qa/post-detalle.png',fullPage:true});
 await page.getByRole('button',{name:'Cerrar',exact:true}).click();
 console.log('Filters, search and detail passed.');
 await page.getByRole('link',{name:'Catálogo',exact:true}).click();
 await page.getByRole('button',{name:'Agregar Post ID',exact:true}).click();
 await page.getByRole('textbox',{name:'Post ID',exact:true}).fill('QA-TEST-001');
 await page.getByRole('textbox',{name:'Nombre del creativo',exact:true}).fill('Creativo de prueba QA');
 await page.getByRole('button',{name:'Guardar Post ID',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 console.log('Catalog form submitted.');
 check(await page.getByText('Creativo de prueba QA',{exact:true}).count()===1,'New demo post must appear');
 await page.getByRole('switch',{name:'Activar QA-TEST-001'}).click();
 console.log('Catalog toggle passed.');
 check(await page.getByRole('switch',{name:'Activar QA-TEST-001'}).getAttribute('aria-checked')==='false','Post toggle must change state');
 await page.getByRole('link',{name:'Ubicaciones',exact:true}).click();
 await page.getByRole('heading',{name:'Ubicaciones',exact:true}).waitFor();
 await page.screenshot({path:'tmp/qa/ubicaciones-desktop.png',fullPage:true});
 await page.getByRole('link',{name:'Calidad',exact:true}).click();
 await page.getByRole('heading',{name:'Calidad',exact:true}).waitFor();
 await page.getByRole('button',{name:'Ver pedidos',exact:true}).click();
 check(await page.getByRole('dialog').count()===1,'Quality detail must open');
 await page.keyboard.press('Escape');
 await page.getByRole('link',{name:'Administración',exact:true}).click();
 await page.getByRole('button',{name:'Integración',exact:true}).click();
 check(await page.getByRole('heading',{name:'Google Sheets · Pedidos Bot'}).count()===1,'Integration instructions must be visible');
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:3000/inicio?demo=1',{waitUntil:'networkidle'});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile layout overflows horizontally');
 await page.screenshot({path:'tmp/qa/inicio-mobile.png',fullPage:true});
 await page.getByRole('navigation',{name:'Navegación móvil'}).getByRole('link',{name:'Post ID',exact:true}).click();
 await page.getByRole('heading',{name:'Post ID',exact:true}).waitFor();
 await page.locator('.mobile-post').first().waitFor();
 check(await page.locator('.mobile-post').count()===11,'Mobile post list must contain all posts');
 await page.locator('.mobile-post').first().click();
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Más',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('dialog').getByRole('link',{name:'Catálogo',exact:true}).click();
 await page.getByRole('heading',{name:'Catálogo',exact:true}).waitFor();
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile catalog overflows horizontally');
 await page.goto('http://127.0.0.1:3000/ingreso',{waitUntil:'networkidle'});
 await page.screenshot({path:'tmp/qa/ingreso-mobile.png',fullPage:true});
 const unauthorized=await page.request.get('http://127.0.0.1:3000/api/snapshot?from=2026-10-01&to=2026-10-14');
 check(unauthorized.status()===401,'Unauthenticated snapshot must return 401');
 const denied=await page.request.post('http://127.0.0.1:3000/api/catalog',{data:{}});
 check(denied.status()===403,'Cross-origin catalog write must return 403');
 check(errors.length===0,'Browser errors: '+errors.join('; '));
 writeFileSync('tmp/qa/report.json',JSON.stringify({status:'passed',checks:18,browserErrors:errors},null,2));
 console.log('18 browser checks passed; no page errors. Screenshots in tmp/qa.');
}finally{await browser.close()}
