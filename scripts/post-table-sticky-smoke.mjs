import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const base=process.env.RADAR_QA_URL??'http://127.0.0.1:3003';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Bogota'}).format(new Date());
const catalog=Array.from({length:65},(_,i)=>({post_id:`POST-${String(i).padStart(4,'0')}`,nombre_creativo:`Publicación ${i}`,producto:'Pulsar 180',campana:'',plataforma:'Otra',activo:true,fecha_inicio:day.slice(0,7)+'-01'}));
const snapshot={mode:'live',profile:{user_id:'qa',nombre:'QA',email:'',role:'analista',activo:true},runs:[],catalog,sales:[],interactions:[]};
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
page.setDefaultTimeout(30000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.route('**/api/snapshot?**',route=>route.fulfill({json:snapshot}));
await page.route('**/api/meta**',route=>route.fulfill({json:{ads:[]}}));
mkdirSync('tmp/qa',{recursive:true});
try{
 await page.goto(base+'/post-id',{waitUntil:'domcontentloaded'});
 await page.locator('.posts-table tbody tr').last().waitFor();
 const controls=page.locator('.posts-scroll-controls'),heading=page.locator('.posts-table thead');
 await controls.waitFor();
 const tableY=(await page.locator('.posts-scroll-viewport').boundingBox()).y;
 await page.evaluate(y=>window.scrollTo(0,y+400),tableY);
 await page.waitForFunction(()=>Math.abs(document.querySelector('.posts-scroll-controls').getBoundingClientRect().top-12)<2);
 await page.waitForFunction(()=>{const controls=document.querySelector('.posts-scroll-controls').getBoundingClientRect(),head=document.querySelector('.posts-table thead').getBoundingClientRect();return Math.abs(head.top-controls.bottom-8)<3});
 const firstX=(await page.locator('.posts-table thead th').first().boundingBox()).x;
 const slider=page.getByRole('slider',{name:'Desplazar columnas de Post ID'});
 await slider.focus();await slider.press('End');
 await page.waitForFunction(()=>{const el=document.querySelector('.posts-scroll-viewport');return el.scrollWidth-el.clientWidth-el.scrollLeft<2});
 assert(Math.abs((await page.locator('.posts-table thead th').first().boundingBox()).x-firstX)<2,'Post ID heading remains pinned horizontally');
 const last=page.getByRole('columnheader',{name:'Estado',exact:true});
 assert((await last.boundingBox()).y>=12,'Last column heading remains visible');
 await last.getByRole('button').click();
 assert.notEqual(await last.getAttribute('aria-sort'),'none','Pinned heading remains interactive');
 await page.screenshot({path:'tmp/qa/post-id-barra-encabezado-fijos.png'});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.waitForFunction(()=>document.querySelector('.posts-table thead').style.transform==='translateY(0px)');
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page does not overflow');
 assert.deepEqual(errors,[]);
 console.log('Sticky Post ID controls and headings passed: page scroll, horizontal alignment, sorting, return to top and mobile fit.');
}finally{await browser.close()}
