import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.RADAR_QA_URL??'http://127.0.0.1:3000';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Bogota'}).format(new Date());
const ads=Array.from({length:500},(_,i)=>({id:`120000${String(i).padStart(6,'0')}`,name:i===321?'Vídeo especial Pulsar':'Publicación '+i,facebookUrl:null,instagramUrl:null,frequency:null,impressions:null,reach:null}));
const snapshot={mode:'live',profile:{user_id:'qa',nombre:'QA',role:'analista',activo:true},catalog:[{post_id:ads[0].id,nombre_creativo:ads[0].name,producto:'Pulsar 180',campana:'',plataforma:'Otra',activo:true,fecha_inicio:day}],sales:[],interactions:[],runs:[]};
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(30000);
const errors=[],saved=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/snapshot?**',route=>route.fulfill({json:snapshot}));
await page.route('**/api/meta?**',route=>route.fulfill({json:{configured:true,ads}}));
await page.route('**/api/catalog',route=>{const post=route.request().postDataJSON();saved.push(post);snapshot.catalog.push(post);return route.fulfill({json:{ok:true}})});
try{
 await page.goto(base+'/catalogo',{waitUntil:'domcontentloaded',timeout:120000});
 await page.getByRole('button',{name:'Agregar Post ID',exact:true}).click();
 const dialog=page.getByRole('dialog');
 const search=dialog.getByRole('searchbox',{name:'Buscar publicación por ID o nombre'});
 const select=dialog.getByLabel('Publicación de Meta',{exact:true});
 await select.locator('option').last().waitFor({state:'attached'});
 await page.waitForFunction(()=>document.querySelector('select[name=post_id]')?.options.length===500);
 await search.fill(ads[0].id);
 await dialog.getByText(`El Post ID ${ads[0].id} ya se encuentra en el catálogo y está asignado a la línea Pulsar 180.`,{exact:true}).waitFor();
 assert.equal(await select.locator('option').count(),1,'Existing IDs cannot be selected or submitted again');
 assert.equal(saved.length,0);
 await search.fill('');
 assert.equal(await select.locator(`option[value="${ads[0].id}"]`).count(),0,'Existing IDs are excluded');
 await search.fill('000321');
 assert.equal(await select.locator('option').count(),2);
 await select.selectOption(ads[321].id);
 await search.fill('vIdEo especial');
 assert.equal(await select.inputValue(),'','A new search clears the previous selection');
 assert.equal(await select.locator('option').count(),2,'Name search ignores case and accents');
 await search.fill('99999999');
 await dialog.getByRole('status').filter({hasText:'No hay coincidencias'}).waitFor();
 assert.equal(await select.locator('option').count(),1);
 await search.fill('');assert.equal(await select.locator('option').count(),500);
 await page.setViewportSize({width:390,height:844});
 await search.fill('000321');await select.selectOption(ads[321].id);
 await dialog.getByLabel('Línea',{exact:true}).fill('Pulsar 180');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await dialog.getByRole('button',{name:'Guardar Post ID',exact:true}).click();
 await dialog.waitFor({state:'hidden'});
 assert.equal(saved.length,1);assert.equal(saved[0].post_id,ads[321].id);assert.equal(saved[0].nombre_creativo,ads[321].name);
 await page.getByRole('button',{name:'Agregar Post ID',exact:true}).click();
 assert.equal(await search.inputValue(),'','Reopening starts a fresh search');
 assert.deepEqual(errors,[]);
 console.log('PASS: 500 publications, partial ID/name search, accents/case, empty results, clear/reset, existing-ID exclusion, mobile and correct saved ID.');
}finally{await browser.close()}
